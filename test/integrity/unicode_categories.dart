// The letter predicate of the integrity suite. A letter is a code point of
// Unicode general category L (Lu, Ll, Lt, Lm, Lo) within the blocks of the
// table below. The table covers Basic Latin and Latin-1 Supplement, whose
// letters the synthetic packs use, and the Arabic blocks. A code point
// outside them is no letter here: the pack text is Arabic, and the gap check
// reports any code point between spans other than the separator.

/// Whether [codePoint] is a letter: general category L* in the table.
bool isLetter(int codePoint) =>
    generalCategory(codePoint)?.startsWith('L') ?? false;

/// `U+` and at least four upper-case hex digits.
String codePointName(int codePoint) =>
    'U+${codePoint.toRadixString(16).toUpperCase().padLeft(4, '0')}';

/// The Unicode general category of [codePoint], from the table below, or
/// null when it lies outside the table's blocks or is unassigned there.
String? generalCategory(int codePoint) {
  var low = 0;
  var high = _runs.length - 1;
  while (low <= high) {
    final mid = (low + high) >> 1;
    final (first, last, category) = _runs[mid];
    if (codePoint < first) {
      high = mid - 1;
    } else if (codePoint > last) {
      low = mid + 1;
    } else {
      return category;
    }
  }
  return null;
}

/// The blocks the table covers, first and last code point.
const coveredBlocks = <(int, int)>[
  (0x0000, 0x007F),
  (0x0080, 0x00FF),
  (0x0600, 0x06FF),
  (0x0750, 0x077F),
  (0x0870, 0x089F),
  (0x08A0, 0x08FF),
  (0xFB50, 0xFDFF),
  (0xFE70, 0xFEFF),
  (0x10EC0, 0x10EFF),
  (0x1EE00, 0x1EEFF),
];

